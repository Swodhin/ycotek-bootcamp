-- Retail Warehouse (Walmart-like synthetic source data)
-- PostgreSQL DDL for Assignment 2.1
-- Design: Snowflake schema; DIM_ITEM and DIM_LOCN are SCD Type 2.

CREATE SCHEMA IF NOT EXISTS retail_warehouse;
SET search_path TO retail_warehouse;

-- -------------------------
-- Dimension tables
-- -------------------------

CREATE TABLE dim_subclass (
    subclass_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subclass_id       VARCHAR(30) NOT NULL UNIQUE,
    subclass_name     VARCHAR(100) NOT NULL,
    category_name     VARCHAR(100) NOT NULL,
    department_name   VARCHAR(100) NOT NULL
);

CREATE TABLE dim_item (
    item_sk           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id           VARCHAR(30) NOT NULL,
    item_name         VARCHAR(150) NOT NULL,
    brand             VARCHAR(100),
    subclass_sk       BIGINT NOT NULL REFERENCES dim_subclass(subclass_sk),
    effective_from    DATE NOT NULL,
    effective_to      DATE NOT NULL DEFAULT DATE '9999-12-31',
    is_current        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_dim_item_dates CHECK (effective_to >= effective_from)
);

CREATE UNIQUE INDEX uq_dim_item_version
    ON dim_item (item_id, effective_from);

CREATE UNIQUE INDEX uq_dim_item_current
    ON dim_item (item_id) WHERE is_current = TRUE;

CREATE TABLE dim_district (
    district_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id       VARCHAR(30) NOT NULL UNIQUE,
    district_name     VARCHAR(100) NOT NULL,
    city              VARCHAR(100) NOT NULL,
    state             VARCHAR(100) NOT NULL,
    country           VARCHAR(100) NOT NULL
);

CREATE TABLE dim_locn (
    locn_sk           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locn_id           VARCHAR(30) NOT NULL,
    locn_name         VARCHAR(150) NOT NULL,
    locn_type         VARCHAR(50) NOT NULL,
    district_sk       BIGINT NOT NULL REFERENCES dim_district(district_sk),
    effective_from    DATE NOT NULL,
    effective_to      DATE NOT NULL DEFAULT DATE '9999-12-31',
    is_current        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_dim_locn_dates CHECK (effective_to >= effective_from)
);

CREATE UNIQUE INDEX uq_dim_locn_version
    ON dim_locn (locn_id, effective_from);

CREATE UNIQUE INDEX uq_dim_locn_current
    ON dim_locn (locn_id) WHERE is_current = TRUE;

CREATE TABLE dim_day (
    day_sk            INTEGER PRIMARY KEY,
    calendar_date     DATE NOT NULL UNIQUE,
    day_number        SMALLINT NOT NULL CHECK (day_number BETWEEN 1 AND 31),
    month_number      SMALLINT NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    month_name        VARCHAR(20) NOT NULL,
    quarter_number    SMALLINT NOT NULL CHECK (quarter_number BETWEEN 1 AND 4),
    year_number       SMALLINT NOT NULL,
    day_name          VARCHAR(20) NOT NULL,
    is_weekend        BOOLEAN NOT NULL
);

CREATE TABLE dim_customer (
    customer_sk       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       VARCHAR(30) NOT NULL UNIQUE,
    customer_name     VARCHAR(150) NOT NULL,
    gender            VARCHAR(20),
    city              VARCHAR(100),
    customer_segment  VARCHAR(50)
);

-- -------------------------
-- Transaction fact
-- Grain: one sales transaction line.
-- -------------------------

CREATE TABLE fct_sales (
    sales_sk              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id        VARCHAR(50) NOT NULL,
    transaction_line_id   INTEGER NOT NULL,
    item_sk               BIGINT NOT NULL REFERENCES dim_item(item_sk),
    locn_sk               BIGINT NOT NULL REFERENCES dim_locn(locn_sk),
    day_sk                INTEGER NOT NULL REFERENCES dim_day(day_sk),
    customer_sk           BIGINT NOT NULL REFERENCES dim_customer(customer_sk),
    quantity_sold         INTEGER NOT NULL CHECK (quantity_sold > 0),
    unit_price            NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    discount_amount       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    sales_amount          NUMERIC(14,2) NOT NULL CHECK (sales_amount >= 0),
    CONSTRAINT uq_fct_sales_line UNIQUE (transaction_id, transaction_line_id)
);

-- -------------------------
-- Positional facts
-- Grain: one item + one location + one effective period.
-- effective_to is inclusive; 9999-12-31 represents an open-ended period.
-- -------------------------

CREATE TABLE fct_inventory (
    inventory_sk      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_sk           BIGINT NOT NULL REFERENCES dim_item(item_sk),
    locn_sk           BIGINT NOT NULL REFERENCES dim_locn(locn_sk),
    effective_from    DATE NOT NULL,
    effective_to      DATE NOT NULL DEFAULT DATE '9999-12-31',
    stock_quantity    INTEGER NOT NULL CHECK (stock_quantity >= 0),
    reorder_level     INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    CONSTRAINT ck_fct_inventory_dates CHECK (effective_to >= effective_from),
    CONSTRAINT uq_fct_inventory_period UNIQUE (item_sk, locn_sk, effective_from)
);

CREATE TABLE fct_price (
    price_sk          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_sk           BIGINT NOT NULL REFERENCES dim_item(item_sk),
    locn_sk           BIGINT NOT NULL REFERENCES dim_locn(locn_sk),
    effective_from    DATE NOT NULL,
    effective_to      DATE NOT NULL DEFAULT DATE '9999-12-31',
    unit_price        NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT ck_fct_price_dates CHECK (effective_to >= effective_from),
    CONSTRAINT uq_fct_price_period UNIQUE (item_sk, locn_sk, effective_from)
);

-- -------------------------
-- Aggregate table
-- Grain: one item + one location + one day.
-- transaction_count is the number of distinct transactions in that grain.
-- -------------------------

CREATE TABLE agg_daily_item_sales (
    day_sk                INTEGER NOT NULL REFERENCES dim_day(day_sk),
    item_sk               BIGINT NOT NULL REFERENCES dim_item(item_sk),
    locn_sk               BIGINT NOT NULL REFERENCES dim_locn(locn_sk),
    total_quantity_sold   BIGINT NOT NULL CHECK (total_quantity_sold >= 0),
    total_sales_amount    NUMERIC(16,2) NOT NULL CHECK (total_sales_amount >= 0),
    transaction_count     BIGINT NOT NULL CHECK (transaction_count >= 0),
    CONSTRAINT pk_agg_daily_item_sales PRIMARY KEY (day_sk, item_sk, locn_sk)
);

-- Seed DIM_DAY separately with a calendar-generation INSERT.
-- Example below generates dates from 2020-01-01 through 2035-12-31.
INSERT INTO dim_day (
    day_sk, calendar_date, day_number, month_number, month_name,
    quarter_number, year_number, day_name, is_weekend
)
SELECT
    TO_CHAR(d::date, 'YYYYMMDD')::INTEGER,
    d::date,
    EXTRACT(DAY FROM d)::SMALLINT,
    EXTRACT(MONTH FROM d)::SMALLINT,
    TO_CHAR(d, 'FMMonth'),
    EXTRACT(QUARTER FROM d)::SMALLINT,
    EXTRACT(YEAR FROM d)::SMALLINT,
    TO_CHAR(d, 'FMDay'),
    EXTRACT(ISODOW FROM d) IN (6, 7)
FROM generate_series(
    DATE '2020-01-01',
    DATE '2035-12-31',
    INTERVAL '1 day'
) AS g(d)
ON CONFLICT (day_sk) DO NOTHING;
