-- ============================================================
-- 3. POS SALES
-- Quarantine invalid rows and duplicate transaction lines.
-- Preserve valid negative RETURN quantities.
-- ============================================================

-- 3.1 Invalid POS records

INSERT INTO SILVER_3.QUARANTINE_RECORDS (
    DATASET_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER,
    REASON, RECORD_DATA
)
SELECT
    'POS_SALES',
    P.SOURCE_FILE,
    P.SOURCE_ROW_NUMBER,
    CASE
        WHEN P.ITEM_ID IS NULL OR TRIM(P.ITEM_ID) = ''
            THEN 'Missing item ID'
        WHEN P.QUANTITY IS NULL
            THEN 'Missing quantity'
        WHEN UPPER(TRIM(P.TRANSACTION_TYPE)) = 'SALE'
             AND P.QUANTITY < 0
            THEN 'Negative quantity for SALE'
        WHEN I.ITEM_ID IS NULL
            THEN 'Item ID not found in Item Master'
        ELSE 'Invalid transaction'
    END,
    OBJECT_CONSTRUCT_KEEP_NULL(P.*)
FROM BRONZE_3.POS_SALES_RAW P
LEFT JOIN (
    SELECT DISTINCT ITEM_ID
    FROM SILVER_3.ITEM_MASTER_CLEAN
) I
    ON TRIM(P.ITEM_ID) = I.ITEM_ID
WHERE P.ITEM_ID IS NULL
   OR TRIM(P.ITEM_ID) = ''
   OR P.QUANTITY IS NULL
   OR (
       UPPER(TRIM(P.TRANSACTION_TYPE)) = 'SALE'
       AND P.QUANTITY < 0
   )
   OR (
       P.ITEM_ID IS NOT NULL
       AND TRIM(P.ITEM_ID) <> ''
       AND I.ITEM_ID IS NULL
   );


-- 3.2 Duplicate POS transaction lines

INSERT INTO SILVER_3.QUARANTINE_RECORDS (
    DATASET_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER,
    REASON, RECORD_DATA
)
SELECT
    'POS_SALES',
    D.SOURCE_FILE,
    D.SOURCE_ROW_NUMBER,
    'Duplicate transaction line',
    OBJECT_CONSTRUCT_KEEP_NULL(D.*)
FROM BRONZE_3.POS_SALES_RAW D
INNER JOIN (
    SELECT DISTINCT ITEM_ID
    FROM SILVER_3.ITEM_MASTER_CLEAN
) I
    ON TRIM(D.ITEM_ID) = I.ITEM_ID
WHERE D.ITEM_ID IS NOT NULL
  AND TRIM(D.ITEM_ID) <> ''
  AND D.QUANTITY IS NOT NULL
  AND NOT (
      UPPER(TRIM(D.TRANSACTION_TYPE)) = 'SALE'
      AND D.QUANTITY < 0
  )
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY
        D.LOCATION_ID,
        D.WORKSTATION_ID,
        D.TRANSACTION_SEQUENCE,
        D.LINE_SEQUENCE,
        D.BUSINESS_DATE,
        D.BEGIN_DATETIME
    ORDER BY D.SOURCE_FILE, D.SOURCE_ROW_NUMBER
) > 1;


-- 3.3 Valid POS records

INSERT INTO SILVER_3.POS_SALES_CLEAN (
    LOCATION_ID, WORKSTATION_ID, TRANSACTION_SEQUENCE,
    LINE_SEQUENCE, BUSINESS_DATE, BEGIN_DATETIME,
    TRANSACTION_TYPE, ITEM_ID, ITEM_SCAN_ID, QUANTITY,
    UNIT_PRICE, EXTENDED_AMOUNT, DISCOUNT_AMOUNT,
    TAX_AMOUNT, NET_AMOUNT, CURRENCY, CASHIER_ID,
    SOURCE_FILE, SOURCE_ROW_NUMBER, INGESTED_AT
)
SELECT
    P.LOCATION_ID,
    P.WORKSTATION_ID,
    P.TRANSACTION_SEQUENCE,
    P.LINE_SEQUENCE,
    P.BUSINESS_DATE,
    P.BEGIN_DATETIME,
    UPPER(TRIM(P.TRANSACTION_TYPE)),
    TRIM(P.ITEM_ID),
    P.ITEM_SCAN_ID,
    P.QUANTITY,
    P.UNIT_PRICE,
    P.EXTENDED_AMOUNT,
    P.DISCOUNT_AMOUNT,
    P.TAX_AMOUNT,
    P.NET_AMOUNT,
    CASE
        WHEN UPPER(TRIM(P.CURRENCY)) = 'US$' THEN 'USD'
        ELSE UPPER(TRIM(P.CURRENCY))
    END,
    P.CASHIER_ID,
    P.SOURCE_FILE,
    P.SOURCE_ROW_NUMBER,
    P.INGESTED_AT
FROM BRONZE_3.POS_SALES_RAW P
INNER JOIN (
    SELECT DISTINCT ITEM_ID
    FROM SILVER_3.ITEM_MASTER_CLEAN
) I
    ON TRIM(P.ITEM_ID) = I.ITEM_ID
WHERE P.ITEM_ID IS NOT NULL
  AND TRIM(P.ITEM_ID) <> ''
  AND P.QUANTITY IS NOT NULL
  AND NOT (
      UPPER(TRIM(P.TRANSACTION_TYPE)) = 'SALE'
      AND P.QUANTITY < 0
  )
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY
        P.LOCATION_ID,
        P.WORKSTATION_ID,
        P.TRANSACTION_SEQUENCE,
        P.LINE_SEQUENCE,
        P.BUSINESS_DATE,
        P.BEGIN_DATETIME
    ORDER BY P.SOURCE_FILE, P.SOURCE_ROW_NUMBER
) = 1;


-- ============================================================
-- 4. INVENTORY SNAPSHOT
-- Quarantine invalid rows and missing item references.
-- Preserve negative stock values.
-- ============================================================

INSERT INTO SILVER_3.QUARANTINE_RECORDS (
    DATASET_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER,
    REASON, RECORD_DATA
)
SELECT
    'INVENTORY',
    R.SOURCE_FILE,
    R.SOURCE_ROW_NUMBER,
    CASE
        WHEN R.ITEM_ID IS NULL OR TRIM(R.ITEM_ID) = ''
            THEN 'Missing item ID'
        WHEN R.LOCATION_ID IS NULL
            THEN 'Missing location ID'
        WHEN R.SNAPSHOT_DATE IS NULL
            THEN 'Missing snapshot date'
        WHEN R.STOCK_ON_HAND IS NULL
            THEN 'Missing stock quantity'
        WHEN I.ITEM_ID IS NULL
            THEN 'Item ID not found in Item Master'
        ELSE 'Invalid inventory record'
    END,
    OBJECT_CONSTRUCT_KEEP_NULL(R.*)
FROM BRONZE_3.INVENTORY_SNAPSHOT_RAW R
LEFT JOIN (
    SELECT DISTINCT ITEM_ID
    FROM SILVER_3.ITEM_MASTER_CLEAN
) I
    ON TRIM(R.ITEM_ID) = I.ITEM_ID
WHERE R.ITEM_ID IS NULL
   OR TRIM(R.ITEM_ID) = ''
   OR R.LOCATION_ID IS NULL
   OR R.SNAPSHOT_DATE IS NULL
   OR R.STOCK_ON_HAND IS NULL
   OR (
       R.ITEM_ID IS NOT NULL
       AND TRIM(R.ITEM_ID) <> ''
       AND I.ITEM_ID IS NULL
   );


INSERT INTO SILVER_3.INVENTORY_SNAPSHOT_CLEAN (
    ITEM_ID, LOCATION_ID, LOCATION_TYPE,
    SNAPSHOT_DATE, STOCK_ON_HAND, SOURCE_FILE,
    SOURCE_ROW_NUMBER, INGESTED_AT
)
SELECT
    TRIM(R.ITEM_ID),
    R.LOCATION_ID,
    UPPER(TRIM(R.LOCATION_TYPE)),
    R.SNAPSHOT_DATE,
    R.STOCK_ON_HAND,
    R.SOURCE_FILE,
    R.SOURCE_ROW_NUMBER,
    R.INGESTED_AT
FROM BRONZE_3.INVENTORY_SNAPSHOT_RAW R
INNER JOIN (
    SELECT DISTINCT ITEM_ID
    FROM SILVER_3.ITEM_MASTER_CLEAN
) I
    ON TRIM(R.ITEM_ID) = I.ITEM_ID
WHERE R.ITEM_ID IS NOT NULL
  AND TRIM(R.ITEM_ID) <> ''
  AND R.LOCATION_ID IS NOT NULL
  AND R.SNAPSHOT_DATE IS NOT NULL
  AND R.STOCK_ON_HAND IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY
        TRIM(R.ITEM_ID),
        R.LOCATION_ID,
        R.SNAPSHOT_DATE
    ORDER BY R.SOURCE_FILE, R.SOURCE_ROW_NUMBER
) = 1;


-- ============================================================
-- 5. STORE REGION MAPPING
-- Standardize region and district names.
-- Keep one valid mapping per store.
-- ============================================================

INSERT INTO SILVER_3.QUARANTINE_RECORDS (
    DATASET_NAME, SOURCE_FILE, SOURCE_ROW_NUMBER,
    REASON, RECORD_DATA
)
SELECT
    'STORE_REGION_MAPPING',
    M.SOURCE_FILE,
    M.SOURCE_ROW_NUMBER,
    CASE
        WHEN M.STORE_ID IS NULL
            THEN 'Missing store ID'
        WHEN M.STORE_CODE IS NULL OR TRIM(M.STORE_CODE) = ''
            THEN 'Missing store code'
        WHEN M.REGION_NAME IS NULL OR TRIM(M.REGION_NAME) = ''
            THEN 'Missing region name'
        WHEN M.DISTRICT_NAME IS NULL OR TRIM(M.DISTRICT_NAME) = ''
            THEN 'Missing district name'
        ELSE 'Invalid region mapping'
    END,
    OBJECT_CONSTRUCT_KEEP_NULL(M.*)
FROM BRONZE_3.STORE_REGION_MAPPING_RAW M
WHERE M.STORE_ID IS NULL
   OR M.STORE_CODE IS NULL
   OR TRIM(M.STORE_CODE) = ''
   OR M.REGION_NAME IS NULL
   OR TRIM(M.REGION_NAME) = ''
   OR M.DISTRICT_NAME IS NULL
   OR TRIM(M.DISTRICT_NAME) = '';


INSERT INTO SILVER_3.STORE_REGION_MAPPING_CLEAN (
    STORE_ID, STORE_CODE, REGION_NAME, DISTRICT_NAME,
    SOURCE_FILE, SOURCE_ROW_NUMBER, INGESTED_AT
)
SELECT
    M.STORE_ID,
    UPPER(TRIM(M.STORE_CODE)),
    TRIM(M.REGION_NAME),
    TRIM(M.DISTRICT_NAME),
    M.SOURCE_FILE,
    M.SOURCE_ROW_NUMBER,
    M.INGESTED_AT
FROM BRONZE_3.STORE_REGION_MAPPING_RAW M
WHERE M.STORE_ID IS NOT NULL
  AND M.STORE_CODE IS NOT NULL
  AND TRIM(M.STORE_CODE) <> ''
  AND M.REGION_NAME IS NOT NULL
  AND TRIM(M.REGION_NAME) <> ''
  AND M.DISTRICT_NAME IS NOT NULL
  AND TRIM(M.DISTRICT_NAME) <> ''
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY M.STORE_ID
    ORDER BY M.SOURCE_FILE, M.SOURCE_ROW_NUMBER
) = 1;
