    ON S.LOCATION_ID = L.STORE_ID
   AND S.BUSINESS_DATE >= L.EFFECTIVE_FROM
   AND (
       S.BUSINESS_DATE <= L.EFFECTIVE_TO
       OR L.EFFECTIVE_TO IS NULL
   )
JOIN GOLD_3.DIM_DATE D
    ON S.BUSINESS_DATE = D.FULL_DATE
WHERE S.BUSINESS_DATE = TO_DATE('{{RUN_DATE}}', 'YYYYMMDD');


-- ============================================================
-- 5. LOAD INVENTORY FACT TABLE
-- Deduplicate snapshots and calculate historical effective dates.
-- ============================================================

MERGE INTO GOLD_3.FCT_INVENTORY T
USING (
    WITH INVENTORY_SOURCE AS (
        SELECT
            ITEM_ID,
            LOCATION_ID,
            SNAPSHOT_DATE,
            STOCK_ON_HAND,
            SOURCE_FILE,
            SOURCE_ROW_NUMBER
        FROM SILVER_3.INVENTORY_SNAPSHOT_CLEAN
        WHERE SNAPSHOT_DATE IS NOT NULL
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ITEM_ID, LOCATION_ID, SNAPSHOT_DATE
            ORDER BY SOURCE_ROW_NUMBER DESC
        ) = 1
    ),

    INVENTORY_TIMELINE AS (
        SELECT
            *,
            SNAPSHOT_DATE AS EFFECTIVE_FROM,
            LEAD(SNAPSHOT_DATE) OVER (
                PARTITION BY ITEM_ID, LOCATION_ID
                ORDER BY SNAPSHOT_DATE
            ) AS NEXT_SNAPSHOT_DATE
        FROM INVENTORY_SOURCE
    )

    SELECT
        I.ITEM_KEY,
        L.LOCATION_KEY,
        D.DATE_KEY,
        S.ITEM_ID,
        S.LOCATION_ID,
        S.SNAPSHOT_DATE,
        S.STOCK_ON_HAND,
        S.SOURCE_FILE,
        S.SOURCE_ROW_NUMBER,
        S.EFFECTIVE_FROM,
        S.NEXT_SNAPSHOT_DATE
    FROM INVENTORY_TIMELINE S
    JOIN GOLD_3.DIM_ITEM I
        ON S.ITEM_ID = I.ITEM_ID
       AND S.SNAPSHOT_DATE >= I.EFFECTIVE_FROM
       AND (
           S.SNAPSHOT_DATE <= I.EFFECTIVE_TO
           OR I.EFFECTIVE_TO IS NULL
       )
    JOIN GOLD_3.DIM_LOCN L
        ON S.LOCATION_ID = L.STORE_ID
       AND S.SNAPSHOT_DATE >= L.EFFECTIVE_FROM
       AND (
           S.SNAPSHOT_DATE <= L.EFFECTIVE_TO
           OR L.EFFECTIVE_TO IS NULL
       )
    JOIN GOLD_3.DIM_DATE D
        ON S.SNAPSHOT_DATE = D.FULL_DATE
) S

ON T.ITEM_ID = S.ITEM_ID
AND T.LOCATION_ID = S.LOCATION_ID
AND T.SNAPSHOT_DATE = S.SNAPSHOT_DATE
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER

WHEN MATCHED THEN UPDATE SET
    T.ITEM_KEY = S.ITEM_KEY,
    T.LOCATION_KEY = S.LOCATION_KEY,
    T.DATE_KEY = S.DATE_KEY,
    T.STOCK_ON_HAND = S.STOCK_ON_HAND,
    T.EFFECTIVE_FROM = S.EFFECTIVE_FROM,
    T.EFFECTIVE_TO = CASE
        WHEN S.NEXT_SNAPSHOT_DATE IS NOT NULL
        THEN DATEADD(DAY, -1, S.NEXT_SNAPSHOT_DATE)
        ELSE NULL
    END,
    T.IS_CURRENT = (S.NEXT_SNAPSHOT_DATE IS NULL),
    T.SOURCE_ROW_ID = S.SOURCE_FILE || ':' || S.SOURCE_ROW_NUMBER

WHEN NOT MATCHED THEN INSERT (
    ITEM_KEY,
    LOCATION_KEY,
    DATE_KEY,
    ITEM_ID,
    LOCATION_ID,
    SNAPSHOT_DATE,
    STOCK_ON_HAND,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    IS_CURRENT,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    SOURCE_ROW_ID
)
VALUES (
    S.ITEM_KEY,
    S.LOCATION_KEY,
    S.DATE_KEY,
    S.ITEM_ID,
    S.LOCATION_ID,
    S.SNAPSHOT_DATE,
    S.STOCK_ON_HAND,
    S.SOURCE_FILE,
    S.SOURCE_ROW_NUMBER,
    S.NEXT_SNAPSHOT_DATE IS NULL,
    S.EFFECTIVE_FROM,
    CASE
        WHEN S.NEXT_SNAPSHOT_DATE IS NOT NULL
        THEN DATEADD(DAY, -1, S.NEXT_SNAPSHOT_DATE)
        ELSE NULL
    END,
    S.SOURCE_FILE || ':' || S.SOURCE_ROW_NUMBER
);


-- ============================================================
-- 6A. DAILY SALES BY ITEM
-- ============================================================

MERGE INTO GOLD_3.RPT_DAILY_SALES_ITEM T
USING (
    SELECT
        D.FULL_DATE AS BUSINESS_DATE,
        I.ITEM_ID,
        SUM(F.QUANTITY) AS TOTAL_QUANTITY,
        SUM(F.NET_AMOUNT) AS TOTAL_NET_SALES,
        COUNT(*) AS TRANSACTION_LINES
    FROM GOLD_3.FCT_SALES F
    JOIN GOLD_3.DIM_DATE D
        ON F.DATE_KEY = D.DATE_KEY
    JOIN GOLD_3.DIM_ITEM I
        ON F.ITEM_KEY = I.ITEM_KEY
    GROUP BY D.FULL_DATE, I.ITEM_ID
) S
ON T.BUSINESS_DATE = S.BUSINESS_DATE
AND T.ITEM_ID = S.ITEM_ID

WHEN MATCHED THEN UPDATE SET
    T.TOTAL_QUANTITY = S.TOTAL_QUANTITY,
    T.TOTAL_NET_SALES = S.TOTAL_NET_SALES,
    T.TRANSACTION_LINES = S.TRANSACTION_LINES

WHEN NOT MATCHED THEN INSERT (
    BUSINESS_DATE,
    ITEM_ID,
    TOTAL_QUANTITY,
    TOTAL_NET_SALES,
    TRANSACTION_LINES
)
VALUES (
    S.BUSINESS_DATE,
    S.ITEM_ID,
    S.TOTAL_QUANTITY,
    S.TOTAL_NET_SALES,
    S.TRANSACTION_LINES
);


