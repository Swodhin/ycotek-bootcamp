-- ============================================================
-- 6E. DAILY SALES BY REGION
-- REGION_ID remains NULL because the source mapping only
-- provides REGION_NAME, not a separate region identifier.
-- ============================================================

MERGE INTO GOLD_3.RPT_DAILY_SALES_REGION T
USING (
    SELECT
        D.FULL_DATE AS BUSINESS_DATE,
        L.REGION_ID,
        COALESCE(L.REGION_NAME, 'UNMAPPED') AS REGION_NAME,
        SUM(F.QUANTITY) AS TOTAL_QUANTITY,
        SUM(F.NET_AMOUNT) AS TOTAL_NET_SALES,
        COUNT(*) AS TRANSACTION_LINES
    FROM GOLD_3.FCT_SALES F
    JOIN GOLD_3.DIM_DATE D
        ON F.DATE_KEY = D.DATE_KEY
    JOIN GOLD_3.DIM_LOCN L
        ON F.LOCATION_KEY = L.LOCATION_KEY
    GROUP BY
        D.FULL_DATE,
        L.REGION_ID,
        COALESCE(L.REGION_NAME, 'UNMAPPED')
) S
ON T.BUSINESS_DATE = S.BUSINESS_DATE
AND T.REGION_ID IS NOT DISTINCT FROM S.REGION_ID
AND T.REGION_NAME = S.REGION_NAME

WHEN MATCHED THEN UPDATE SET
    T.TOTAL_QUANTITY = S.TOTAL_QUANTITY,
    T.TOTAL_NET_SALES = S.TOTAL_NET_SALES,
    T.TRANSACTION_LINES = S.TRANSACTION_LINES

WHEN NOT MATCHED THEN INSERT (
    BUSINESS_DATE,
    REGION_ID,
    REGION_NAME,
    TOTAL_QUANTITY,
    TOTAL_NET_SALES,
    TRANSACTION_LINES
)
VALUES (
    S.BUSINESS_DATE,
    S.REGION_ID,
    S.REGION_NAME,
    S.TOTAL_QUANTITY,
    S.TOTAL_NET_SALES,
    S.TRANSACTION_LINES
);


-- ============================================================
-- 6F. DAILY INVENTORY REPORT
-- ============================================================

MERGE INTO GOLD_3.RPT_DAILY_INVENTORY T
USING (
    SELECT
        SNAPSHOT_DATE,
        ITEM_ID,
        LOCATION_ID,
        SUM(STOCK_ON_HAND) AS STOCK_ON_HAND
    FROM GOLD_3.FCT_INVENTORY
    GROUP BY
        SNAPSHOT_DATE,
        ITEM_ID,
        LOCATION_ID
) S
ON T.SNAPSHOT_DATE = S.SNAPSHOT_DATE
AND T.ITEM_ID = S.ITEM_ID
AND T.LOCATION_ID = S.LOCATION_ID

WHEN MATCHED THEN UPDATE SET
    T.STOCK_ON_HAND = S.STOCK_ON_HAND,
    T.LOADED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    SNAPSHOT_DATE,
    ITEM_ID,
    LOCATION_ID,
    STOCK_ON_HAND
)
VALUES (
    S.SNAPSHOT_DATE,
    S.ITEM_ID,
    S.LOCATION_ID,
    S.STOCK_ON_HAND
);