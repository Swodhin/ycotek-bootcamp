
USE DATABASE RETAIL_DW;

-- ============================================================
-- 1. POPULATE DATE DIMENSION
-- ============================================================

MERGE INTO GOLD_3.DIM_DATE T
USING (
    SELECT DATEADD(DAY, SEQ4(), '2026-10-01'::DATE) AS FULL_DATE
    FROM TABLE(GENERATOR(ROWCOUNT => 5))
) S
ON T.FULL_DATE = S.FULL_DATE
WHEN NOT MATCHED THEN INSERT (
    DATE_KEY, FULL_DATE, DAY_NUMBER, DAY_NAME,
    WEEK_NUMBER, MONTH_NUMBER, MONTH_NAME,
    QUARTER_NUMBER, YEAR_NUMBER, IS_WEEKEND
)
VALUES (
    TO_NUMBER(TO_CHAR(S.FULL_DATE, 'YYYYMMDD')),
    S.FULL_DATE,
    DAY(S.FULL_DATE),
    DAYNAME(S.FULL_DATE),
    WEEKISO(S.FULL_DATE),
    MONTH(S.FULL_DATE),
    MONTHNAME(S.FULL_DATE),
    QUARTER(S.FULL_DATE),
    YEAR(S.FULL_DATE),
    DAYOFWEEKISO(S.FULL_DATE) IN (6, 7)
);


-- ============================================================
-- 2. POPULATE ITEM DIMENSION - SCD TYPE 2
-- ============================================================

MERGE INTO GOLD_3.DIM_ITEM T
USING (
    WITH ITEM_SNAPSHOTS AS (
        SELECT
            ITEM_ID,
            ITEM_PARENT,
            ITEM_LEVEL,
            DEPT_ID,
            CLASS_ID,
            SUBCLASS_ID,
            TO_DATE(
                REGEXP_SUBSTR(SOURCE_FILE, '[0-9]{8}'),
                'YYYYMMDD'
            ) AS SNAPSHOT_DATE
        FROM SILVER_3.ITEM_MASTER_CLEAN
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ITEM_ID,
                TO_DATE(REGEXP_SUBSTR(SOURCE_FILE, '[0-9]{8}'), 'YYYYMMDD')
            ORDER BY SOURCE_ROW_NUMBER DESC
        ) = 1
    ),

    ITEM_HASHES AS (
        SELECT *,
            HASH(
                ITEM_PARENT,
                ITEM_LEVEL,
                DEPT_ID,
                CLASS_ID,
                SUBCLASS_ID
            ) AS ATTRIBUTE_HASH
        FROM ITEM_SNAPSHOTS
    ),

    ITEM_CHANGES AS (
        SELECT *,
            LAG(ATTRIBUTE_HASH) OVER (
                PARTITION BY ITEM_ID
                ORDER BY SNAPSHOT_DATE
            ) AS PREVIOUS_HASH
        FROM ITEM_HASHES
    ),

    ITEM_VERSIONS AS (
        SELECT
            ITEM_ID,
            ITEM_PARENT,
            ITEM_LEVEL,
            DEPT_ID,
            CLASS_ID,
            SUBCLASS_ID,
            SNAPSHOT_DATE AS EFFECTIVE_FROM,
            LEAD(SNAPSHOT_DATE) OVER (
                PARTITION BY ITEM_ID
                ORDER BY SNAPSHOT_DATE
            ) AS NEXT_EFFECTIVE_FROM
        FROM ITEM_CHANGES
        WHERE PREVIOUS_HASH IS NULL
           OR ATTRIBUTE_HASH <> PREVIOUS_HASH
    )

    SELECT
        ITEM_ID,
        ITEM_PARENT,
        ITEM_LEVEL,
        DEPT_ID,
        CLASS_ID,
        SUBCLASS_ID,
        EFFECTIVE_FROM,
        DATEADD(DAY, -1, NEXT_EFFECTIVE_FROM) AS EFFECTIVE_TO,
        NEXT_EFFECTIVE_FROM IS NULL AS IS_CURRENT
    FROM ITEM_VERSIONS
) S
ON T.ITEM_ID = S.ITEM_ID
AND T.EFFECTIVE_FROM = S.EFFECTIVE_FROM

WHEN MATCHED THEN UPDATE SET
    T.ITEM_PARENT = S.ITEM_PARENT,
    T.ITEM_LEVEL = S.ITEM_LEVEL,
    T.DEPT_ID = S.DEPT_ID,
    T.CLASS_ID = S.CLASS_ID,
    T.SUBCLASS_ID = S.SUBCLASS_ID,
    T.EFFECTIVE_TO = S.EFFECTIVE_TO,
    T.IS_CURRENT = S.IS_CURRENT,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    ITEM_ID,
    ITEM_PARENT,
    ITEM_LEVEL,
    DEPT_ID,
    CLASS_ID,
    SUBCLASS_ID,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT
)
VALUES (
    S.ITEM_ID,
    S.ITEM_PARENT,
    S.ITEM_LEVEL,
    S.DEPT_ID,
    S.CLASS_ID,
    S.SUBCLASS_ID,
    S.EFFECTIVE_FROM,
    S.EFFECTIVE_TO,
    S.IS_CURRENT
);


