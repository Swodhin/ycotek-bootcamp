-- ============================================================
-- 1. POPULATE DATE DIMENSION
-- Include all dates required by sales and inventory facts.
-- ============================================================

MERGE INTO GOLD_3.DIM_DATE T
USING (
    SELECT TO_DATE('{{RUN_DATE}}', 'YYYYMMDD') AS FULL_DATE

    UNION

    SELECT BUSINESS_DATE
    FROM SILVER_3.POS_SALES_CLEAN
    WHERE BUSINESS_DATE IS NOT NULL

    UNION

    SELECT SNAPSHOT_DATE
    FROM SILVER_3.INVENTORY_SNAPSHOT_CLEAN
    WHERE SNAPSHOT_DATE IS NOT NULL
) S
ON T.FULL_DATE = S.FULL_DATE

WHEN NOT MATCHED THEN INSERT (
    DATE_KEY,
    FULL_DATE,
    DAY_NUMBER,
    DAY_NAME,
    WEEK_NUMBER,
    MONTH_NUMBER,
    MONTH_NAME,
    QUARTER_NUMBER,
    YEAR_NUMBER,
    IS_WEEKEND
)
VALUES (
    TO_NUMBER(TO_CHAR(S.FULL_DATE, 'YYYYMMDD')),
    S.FULL_DATE,
    DAY(S.FULL_DATE),
    DAYNAME(S.FULL_DATE),
    WEEKISO(S.FULL_DATE),
    MONTH(S.FULL_DATE),
    MONTHNAME(S.FULL_DATE),
    QUARTER(S.FULL_DATE),
    YEAR(S.FULL_DATE),
    DAYOFWEEKISO(S.FULL_DATE) IN (6, 7)
);


-- ============================================================
-- 2. POPULATE ITEM DIMENSION - SCD TYPE 2
-- Process all available Silver snapshots.
-- ============================================================

MERGE INTO GOLD_3.DIM_ITEM T
USING (
    WITH ITEM_SNAPSHOTS AS (
        SELECT
            ITEM_ID,
            ITEM_PARENT,
            ITEM_LEVEL,
            DEPT_ID,
            CLASS_ID,
            SUBCLASS_ID,
            SNAPSHOT_DATE
        FROM SILVER_3.ITEM_MASTER_CLEAN
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ITEM_ID, SNAPSHOT_DATE
            ORDER BY SOURCE_ROW_NUMBER DESC
        ) = 1
    ),

    ITEM_HASHES AS (
        SELECT
            *,
            HASH(
                ITEM_PARENT,
                ITEM_LEVEL,
                DEPT_ID,
                CLASS_ID,
                SUBCLASS_ID
            ) AS ATTRIBUTE_HASH
        FROM ITEM_SNAPSHOTS
    ),

    ITEM_CHANGES AS (
        SELECT
            *,
            LAG(ATTRIBUTE_HASH) OVER (
                PARTITION BY ITEM_ID
                ORDER BY SNAPSHOT_DATE
            ) AS PREVIOUS_HASH
        FROM ITEM_HASHES
    ),

    ITEM_VERSIONS AS (
        SELECT
            ITEM_ID,
            ITEM_PARENT,
            ITEM_LEVEL,
            DEPT_ID,
            CLASS_ID,
            SUBCLASS_ID,
            SNAPSHOT_DATE AS EFFECTIVE_FROM,
            LEAD(SNAPSHOT_DATE) OVER (
                PARTITION BY ITEM_ID
                ORDER BY SNAPSHOT_DATE
            ) AS NEXT_EFFECTIVE_FROM
        FROM ITEM_CHANGES
        WHERE PREVIOUS_HASH IS NULL
           OR ATTRIBUTE_HASH <> PREVIOUS_HASH
    )

    SELECT
        ITEM_ID,
        ITEM_PARENT,
        ITEM_LEVEL,
        DEPT_ID,
        CLASS_ID,
        SUBCLASS_ID,
        EFFECTIVE_FROM,
        DATEADD(DAY, -1, NEXT_EFFECTIVE_FROM) AS EFFECTIVE_TO,
        NEXT_EFFECTIVE_FROM IS NULL AS IS_CURRENT
    FROM ITEM_VERSIONS
) S
ON T.ITEM_ID = S.ITEM_ID
AND T.EFFECTIVE_FROM = S.EFFECTIVE_FROM

WHEN MATCHED THEN UPDATE SET
    T.ITEM_PARENT = S.ITEM_PARENT,
    T.ITEM_LEVEL = S.ITEM_LEVEL,
    T.DEPT_ID = S.DEPT_ID,
    T.CLASS_ID = S.CLASS_ID,
    T.SUBCLASS_ID = S.SUBCLASS_ID,
    T.EFFECTIVE_TO = S.EFFECTIVE_TO,
    T.IS_CURRENT = S.IS_CURRENT,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    ITEM_ID,
    ITEM_PARENT,
    ITEM_LEVEL,
    DEPT_ID,
    CLASS_ID,
    SUBCLASS_ID,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT
)
VALUES (
    S.ITEM_ID,
    S.ITEM_PARENT,
    S.ITEM_LEVEL,
    S.DEPT_ID,
    S.CLASS_ID,
    S.SUBCLASS_ID,
    S.EFFECTIVE_FROM,
    S.EFFECTIVE_TO,
    S.IS_CURRENT
);


-- ============================================================
-- 3. POPULATE LOCATION DIMENSION - SCD TYPE 2
-- Process genuine store attribute changes only.
-- ============================================================

-- 3.0 Build and merge actual location versions.
-- Keep existing current records active until the MERGE completes.

MERGE INTO GOLD_3.DIM_LOCN T
USING (
    WITH STORE_SNAPSHOTS AS (
        SELECT
            SM.STORE_ID,
            SM.STORE_NAME,
            SM.STORE_NAME10,
            SM.STORE_TYPE,
            SM.DISTRICT_ID::VARCHAR AS DISTRICT_ID,
            M.DISTRICT_NAME,
            CAST(NULL AS VARCHAR) AS REGION_ID,
            M.REGION_NAME,
            SM.CHANNEL_ID,
            SM.COUNTRY,
            SM.STATE,
            SM.CITY,
            SM.SNAPSHOT_DATE
        FROM SILVER_3.STORE_MASTER_CLEAN SM
        LEFT JOIN SILVER_3.STORE_REGION_MAPPING_CLEAN M
            ON SM.STORE_ID = M.STORE_ID
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY SM.STORE_ID, SM.SNAPSHOT_DATE
            ORDER BY SM.SOURCE_ROW_NUMBER DESC
        ) = 1
    ),

    SOURCE_HASHES AS (
        SELECT *,
            HASH(
                STORE_NAME, STORE_TYPE, DISTRICT_ID,
                DISTRICT_NAME, REGION_NAME, CHANNEL_ID,
                COUNTRY, STATE, CITY
            ) AS ATTRIBUTE_HASH
        FROM STORE_SNAPSHOTS
    ),

    CURRENT_LOCN AS (
        SELECT
            STORE_ID,
            EFFECTIVE_FROM,
            HASH(
                STORE_NAME, STORE_TYPE, DISTRICT_ID,
                DISTRICT_NAME, REGION_NAME, CHANNEL_ID,
                COUNTRY, STATE, CITY
            ) AS CURRENT_HASH
        FROM GOLD_3.DIM_LOCN
        WHERE IS_CURRENT = TRUE
    ),

    SOURCE_CHANGES AS (
        SELECT
            S.*,
            LAG(ATTRIBUTE_HASH) OVER (
                PARTITION BY S.STORE_ID
                ORDER BY S.SNAPSHOT_DATE
            ) AS PREVIOUS_HASH,
            ROW_NUMBER() OVER (
                PARTITION BY S.STORE_ID
                ORDER BY S.SNAPSHOT_DATE
            ) AS SNAPSHOT_SEQUENCE,
            C.EFFECTIVE_FROM AS CURRENT_EFFECTIVE_FROM,
            C.CURRENT_HASH
        FROM SOURCE_HASHES S
        LEFT JOIN CURRENT_LOCN C
            ON S.STORE_ID = C.STORE_ID
    ),

    ACTUAL_CHANGES AS (
        SELECT *
        FROM SOURCE_CHANGES
        WHERE SNAPSHOT_DATE >
              COALESCE(CURRENT_EFFECTIVE_FROM, '1900-01-01'::DATE)
          AND (
              (
                  SNAPSHOT_SEQUENCE = 1
                  AND (
                      CURRENT_EFFECTIVE_FROM IS NULL
                      OR ATTRIBUTE_HASH IS DISTINCT FROM CURRENT_HASH
                  )
              )
              OR (
                  SNAPSHOT_SEQUENCE > 1
                  AND ATTRIBUTE_HASH IS DISTINCT FROM PREVIOUS_HASH
              )
          )
    ),

    STORE_VERSIONS AS (
        SELECT
            *,
            LEAD(SNAPSHOT_DATE) OVER (
                PARTITION BY STORE_ID
                ORDER BY SNAPSHOT_DATE
            ) AS NEXT_EFFECTIVE_FROM
        FROM ACTUAL_CHANGES
    )

    SELECT
        STORE_ID,
        STORE_NAME,
        STORE_NAME10,
        STORE_TYPE,
        DISTRICT_ID,
        DISTRICT_NAME,
        REGION_ID,
        REGION_NAME,
        CHANNEL_ID,
        COUNTRY,
        STATE,
        CITY,
        SNAPSHOT_DATE AS EFFECTIVE_FROM,
        DATEADD(DAY, -1, NEXT_EFFECTIVE_FROM) AS EFFECTIVE_TO,
        NEXT_EFFECTIVE_FROM IS NULL AS IS_CURRENT
    FROM STORE_VERSIONS
) S
ON T.STORE_ID = S.STORE_ID
AND T.EFFECTIVE_FROM = S.EFFECTIVE_FROM

WHEN MATCHED THEN UPDATE SET
    T.STORE_NAME = S.STORE_NAME,
    T.STORE_NAME10 = S.STORE_NAME10,
    T.STORE_TYPE = S.STORE_TYPE,
    T.DISTRICT_ID = S.DISTRICT_ID,
    T.DISTRICT_NAME = S.DISTRICT_NAME,
    T.REGION_ID = S.REGION_ID,
    T.REGION_NAME = S.REGION_NAME,
    T.CHANNEL_ID = S.CHANNEL_ID,
    T.COUNTRY = S.COUNTRY,
    T.STATE = S.STATE,
    T.CITY = S.CITY,
    T.EFFECTIVE_TO = S.EFFECTIVE_TO,
    T.IS_CURRENT = S.IS_CURRENT,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    STORE_ID, STORE_NAME, STORE_NAME10, STORE_TYPE,
    DISTRICT_ID, DISTRICT_NAME, REGION_ID, REGION_NAME,
    CHANNEL_ID, COUNTRY, STATE, CITY,
    EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT
)
VALUES (
    S.STORE_ID, S.STORE_NAME, S.STORE_NAME10, S.STORE_TYPE,
    S.DISTRICT_ID, S.DISTRICT_NAME, S.REGION_ID, S.REGION_NAME,
    S.CHANNEL_ID, S.COUNTRY, S.STATE, S.CITY,
    S.EFFECTIVE_FROM, S.EFFECTIVE_TO, S.IS_CURRENT
);


-- 3.0.1 Expire previous current versions after the MERGE.
-- A current record is expired only when a later version exists.

UPDATE GOLD_3.DIM_LOCN T
SET
    EFFECTIVE_TO = DATEADD(DAY, -1, S.NEXT_EFFECTIVE_FROM),
    IS_CURRENT = FALSE,
    UPDATED_AT = CURRENT_TIMESTAMP()
FROM (
    SELECT
        STORE_ID,
        EFFECTIVE_FROM,
        LEAD(EFFECTIVE_FROM) OVER (
            PARTITION BY STORE_ID
            ORDER BY EFFECTIVE_FROM
        ) AS NEXT_EFFECTIVE_FROM
    FROM GOLD_3.DIM_LOCN
) S
WHERE T.STORE_ID = S.STORE_ID
  AND T.EFFECTIVE_FROM = S.EFFECTIVE_FROM
  AND T.IS_CURRENT = TRUE
  AND S.NEXT_EFFECTIVE_FROM IS NOT NULL;


-- ============================================================
-- 3.1 SCD TYPE 1: STORE_NAME10
-- Update STORE_NAME10 across all versions for each store.
-- ============================================================

UPDATE GOLD_3.DIM_LOCN T
SET
    STORE_NAME10 = S.STORE_NAME10,
    UPDATED_AT = CURRENT_TIMESTAMP()
FROM (
    SELECT
        STORE_ID,
        STORE_NAME10
    FROM SILVER_3.STORE_MASTER_CLEAN
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY STORE_ID
        ORDER BY SNAPSHOT_DATE DESC, SOURCE_ROW_NUMBER DESC
    ) = 1
) S
WHERE T.STORE_ID = S.STORE_ID
  AND T.STORE_NAME10 IS DISTINCT FROM S.STORE_NAME10;


