-- 3.1 SCD Type 2: Insert stores that do not exist yet
-- Use the latest available store snapshot.

MERGE INTO GOLD_3.DIM_LOCN T
USING (
    SELECT
        S.STORE_ID,
        S.STORE_NAME,
        S.STORE_NAME10,
        S.STORE_TYPE,
        S.DISTRICT_ID::VARCHAR AS DISTRICT_ID,
        M.REGION_NAME,
        M.DISTRICT_NAME,
        S.CHANNEL_ID,
        S.COUNTRY,
        S.STATE,
        S.CITY,
        S.SNAPSHOT_DATE AS EFFECTIVE_FROM
    FROM SILVER_3.STORE_MASTER_CLEAN S
    LEFT JOIN SILVER_3.STORE_REGION_MAPPING_CLEAN M
        ON S.STORE_ID = M.STORE_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY S.STORE_ID
        ORDER BY S.SNAPSHOT_DATE DESC, S.SOURCE_ROW_NUMBER
    ) = 1
) S
ON T.STORE_ID = S.STORE_ID
AND T.IS_CURRENT = TRUE

WHEN NOT MATCHED THEN INSERT (
    STORE_ID, STORE_NAME, STORE_NAME10, STORE_TYPE,
    DISTRICT_ID, REGION_ID, DISTRICT_NAME, REGION_NAME,
    CHANNEL_ID, COUNTRY, STATE, CITY,
    EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT
)
VALUES (
    S.STORE_ID, S.STORE_NAME, S.STORE_NAME10, S.STORE_TYPE,
    S.DISTRICT_ID, NULL, S.DISTRICT_NAME, S.REGION_NAME,
    S.CHANNEL_ID, S.COUNTRY, S.STATE, S.CITY,
    S.EFFECTIVE_FROM, NULL, TRUE
);


-- 3.2 SCD Type 1: Update STORE_NAME10 in place

UPDATE GOLD_3.DIM_LOCN T
SET
    STORE_NAME10 = S.STORE_NAME10,
    UPDATED_AT = CURRENT_TIMESTAMP()
FROM (
    SELECT *
    FROM SILVER_3.STORE_MASTER_CLEAN
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY STORE_ID
        ORDER BY SNAPSHOT_DATE DESC, SOURCE_ROW_NUMBER
    ) = 1
) S
WHERE T.STORE_ID = S.STORE_ID
  AND T.IS_CURRENT = TRUE
  AND T.STORE_NAME10 IS DISTINCT FROM S.STORE_NAME10;


-- 3.3 SCD Type 2: Expire changed location records

UPDATE GOLD_3.DIM_LOCN T
SET
    EFFECTIVE_TO = DATEADD(DAY, -1, S.SNAPSHOT_DATE),
    IS_CURRENT = FALSE,
    UPDATED_AT = CURRENT_TIMESTAMP()
FROM (
    SELECT
        SM.*,
        M.DISTRICT_NAME,
        M.REGION_NAME
    FROM SILVER_3.STORE_MASTER_CLEAN SM
    LEFT JOIN SILVER_3.STORE_REGION_MAPPING_CLEAN M
        ON SM.STORE_ID = M.STORE_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SM.STORE_ID
        ORDER BY SM.SNAPSHOT_DATE DESC, SM.SOURCE_ROW_NUMBER
    ) = 1
) S
WHERE T.STORE_ID = S.STORE_ID
  AND T.IS_CURRENT = TRUE
  AND S.SNAPSHOT_DATE > T.EFFECTIVE_FROM
  AND (
      T.STORE_NAME IS DISTINCT FROM S.STORE_NAME
      OR T.STORE_TYPE IS DISTINCT FROM S.STORE_TYPE
      OR T.DISTRICT_ID IS DISTINCT FROM S.DISTRICT_ID::VARCHAR
      OR T.CHANNEL_ID IS DISTINCT FROM S.CHANNEL_ID
      OR T.COUNTRY IS DISTINCT FROM S.COUNTRY
      OR T.STATE IS DISTINCT FROM S.STATE
      OR T.CITY IS DISTINCT FROM S.CITY
      OR T.DISTRICT_NAME IS DISTINCT FROM S.DISTRICT_NAME
      OR T.REGION_NAME IS DISTINCT FROM S.REGION_NAME
  );


-- 3.4 SCD Type 2: Insert new current location records

INSERT INTO GOLD_3.DIM_LOCN (
    STORE_ID, STORE_NAME, STORE_NAME10, STORE_TYPE,
    DISTRICT_ID, REGION_ID, DISTRICT_NAME, REGION_NAME,
    CHANNEL_ID, COUNTRY, STATE, CITY,
    EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT
)
SELECT
    S.STORE_ID,
    S.STORE_NAME,
    S.STORE_NAME10,
    S.STORE_TYPE,
    S.DISTRICT_ID::VARCHAR,
    NULL,
    S.DISTRICT_NAME,
    S.REGION_NAME,
    S.CHANNEL_ID,
    S.COUNTRY,
    S.STATE,
    S.CITY,
    S.SNAPSHOT_DATE,
    NULL,
    TRUE
FROM (
    SELECT
        SM.*,
        M.DISTRICT_NAME,
        M.REGION_NAME
    FROM SILVER_3.STORE_MASTER_CLEAN SM
    LEFT JOIN SILVER_3.STORE_REGION_MAPPING_CLEAN M
        ON SM.STORE_ID = M.STORE_ID
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SM.STORE_ID
        ORDER BY SM.SNAPSHOT_DATE DESC, SM.SOURCE_ROW_NUMBER
    ) = 1
) S
WHERE NOT EXISTS (
    SELECT 1
    FROM GOLD_3.DIM_LOCN T
    WHERE T.STORE_ID = S.STORE_ID
      AND T.IS_CURRENT = TRUE
);


-- ============================================================
-- 4. LOAD SALES FACT TABLE
-- ============================================================

-- Remove old Gold rows for POS files currently present in Bronze.
-- The MERGE below reloads only the valid Silver records.

DELETE FROM GOLD_3.FCT_SALES
WHERE SOURCE_FILE IN (
    SELECT DISTINCT SOURCE_FILE
    FROM BRONZE_3.POS_SALES_RAW
);

MERGE INTO GOLD_3.FCT_SALES T
USING (
    SELECT
        I.ITEM_KEY,
        L.LOCATION_KEY,
        D.DATE_KEY,
        S.LOCATION_ID,
        S.WORKSTATION_ID,
        S.TRANSACTION_SEQUENCE,
        S.LINE_SEQUENCE,
        S.TRANSACTION_TYPE,
        S.QUANTITY,
        S.UNIT_PRICE,
        S.EXTENDED_AMOUNT,
        S.DISCOUNT_AMOUNT,
        S.TAX_AMOUNT,
        S.NET_AMOUNT,
        S.CURRENCY,
        S.SOURCE_FILE,
        S.SOURCE_ROW_NUMBER
    FROM SILVER_3.POS_SALES_CLEAN S
    JOIN GOLD_3.DIM_ITEM I
        ON S.ITEM_ID = I.ITEM_ID
       AND S.BUSINESS_DATE >= I.EFFECTIVE_FROM
       AND (S.BUSINESS_DATE <= I.EFFECTIVE_TO OR I.EFFECTIVE_TO IS NULL)
    JOIN GOLD_3.DIM_LOCN L
        ON S.LOCATION_ID = L.STORE_ID
       AND S.BUSINESS_DATE >= L.EFFECTIVE_FROM
       AND (S.BUSINESS_DATE <= L.EFFECTIVE_TO OR L.EFFECTIVE_TO IS NULL)
    JOIN GOLD_3.DIM_DATE D
        ON S.BUSINESS_DATE = D.FULL_DATE
) S
ON T.LOCATION_ID = S.LOCATION_ID
AND T.WORKSTATION_ID = S.WORKSTATION_ID
AND T.TRANSACTION_SEQUENCE = S.TRANSACTION_SEQUENCE
AND T.LINE_SEQUENCE = S.LINE_SEQUENCE
AND T.DATE_KEY = S.DATE_KEY
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER

WHEN NOT MATCHED THEN INSERT (
    ITEM_KEY,
    LOCATION_KEY,
    DATE_KEY,
    LOCATION_ID,
    WORKSTATION_ID,
    TRANSACTION_SEQUENCE,
    LINE_SEQUENCE,
    TRANSACTION_TYPE,
    QUANTITY,
    UNIT_PRICE,
    EXTENDED_AMOUNT,
    DISCOUNT_AMOUNT,
    TAX_AMOUNT,
    NET_AMOUNT,
    CURRENCY,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER
)
VALUES (
    S.ITEM_KEY,
    S.LOCATION_KEY,
    S.DATE_KEY,
    S.LOCATION_ID,
    S.WORKSTATION_ID,
    S.TRANSACTION_SEQUENCE,
    S.LINE_SEQUENCE,
    S.TRANSACTION_TYPE,
    S.QUANTITY,
    S.UNIT_PRICE,
    S.EXTENDED_AMOUNT,
    S.DISCOUNT_AMOUNT,
    S.TAX_AMOUNT,
    S.NET_AMOUNT,
    S.CURRENCY,
    S.SOURCE_FILE,
    S.SOURCE_ROW_NUMBER
);


-- ============================================================
-- 5. LOAD INVENTORY FACT TABLE
-- ============================================================


MERGE INTO GOLD_3.FCT_INVENTORY T
USING (
    SELECT
        I.ITEM_KEY,
        L.LOCATION_KEY,
        D.DATE_KEY,
        S.ITEM_ID,
        S.LOCATION_ID,
        S.SNAPSHOT_DATE,
        S.STOCK_ON_HAND,
        S.SOURCE_FILE,
        S.SOURCE_ROW_NUMBER,
        S.SNAPSHOT_DATE AS EFFECTIVE_FROM,
        LEAD(S.SNAPSHOT_DATE) OVER (
            PARTITION BY S.ITEM_ID, S.LOCATION_ID
            ORDER BY S.SNAPSHOT_DATE
        ) AS NEXT_SNAPSHOT_DATE
    FROM SILVER_3.INVENTORY_SNAPSHOT_CLEAN S
    JOIN GOLD_3.DIM_ITEM I
        ON S.ITEM_ID = I.ITEM_ID
       AND S.SNAPSHOT_DATE >= I.EFFECTIVE_FROM
       AND (S.SNAPSHOT_DATE <= I.EFFECTIVE_TO OR I.EFFECTIVE_TO IS NULL)
    JOIN GOLD_3.DIM_LOCN L
        ON S.LOCATION_ID = L.STORE_ID
       AND S.SNAPSHOT_DATE >= L.EFFECTIVE_FROM
       AND (S.SNAPSHOT_DATE <= L.EFFECTIVE_TO OR L.EFFECTIVE_TO IS NULL)
    JOIN GOLD_3.DIM_DATE D
        ON S.SNAPSHOT_DATE = D.FULL_DATE
) S
ON T.ITEM_ID = S.ITEM_ID
AND T.LOCATION_ID = S.LOCATION_ID
AND T.SNAPSHOT_DATE = S.SNAPSHOT_DATE
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.SOURCE_ROW_NUMBER = S.SOURCE_ROW_NUMBER

WHEN MATCHED THEN UPDATE SET
    T.ITEM_KEY = S.ITEM_KEY,
    T.LOCATION_KEY = S.LOCATION_KEY,
    T.DATE_KEY = S.DATE_KEY,
    T.STOCK_ON_HAND = S.STOCK_ON_HAND,
    T.EFFECTIVE_FROM = S.EFFECTIVE_FROM,
    T.EFFECTIVE_TO = CASE
        WHEN S.NEXT_SNAPSHOT_DATE IS NOT NULL
        THEN DATEADD(DAY, -1, S.NEXT_SNAPSHOT_DATE)
        ELSE NULL
    END,
    T.IS_CURRENT = (S.NEXT_SNAPSHOT_DATE IS NULL)

WHEN NOT MATCHED THEN INSERT (
    ITEM_KEY,
    LOCATION_KEY,
    DATE_KEY,
    ITEM_ID,
    LOCATION_ID,
    SNAPSHOT_DATE,
    STOCK_ON_HAND,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT
)
VALUES (
    S.ITEM_KEY,
    S.LOCATION_KEY,
    S.DATE_KEY,
    S.ITEM_ID,
    S.LOCATION_ID,
    S.SNAPSHOT_DATE,
    S.STOCK_ON_HAND,
    S.SOURCE_FILE,
    S.SOURCE_ROW_NUMBER,
    S.EFFECTIVE_FROM,
    CASE
        WHEN S.NEXT_SNAPSHOT_DATE IS NOT NULL
        THEN DATEADD(DAY, -1, S.NEXT_SNAPSHOT_DATE)
        ELSE NULL
    END,
    S.NEXT_SNAPSHOT_DATE IS NULL
);

