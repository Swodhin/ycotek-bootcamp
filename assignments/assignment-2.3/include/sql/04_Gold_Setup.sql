USE DATABASE RETAIL_DW;

CREATE SCHEMA IF NOT EXISTS GOLD_3;


-- ============================================================
-- 1. DIM_ITEM
-- SCD TYPE 2
-- ============================================================

CREATE TABLE IF NOT EXISTS GOLD_3.DIM_ITEM (
    ITEM_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    ITEM_ID VARCHAR NOT NULL,
    ITEM_PARENT VARCHAR,
    ITEM_LEVEL NUMBER,
    DEPT_ID VARCHAR,
    CLASS_ID VARCHAR,
    SUBCLASS_ID VARCHAR,
    EFFECTIVE_FROM DATE,
    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- ============================================================
-- 2. DIM_LOCN
-- SCD TYPE 2 + SCD TYPE 1
-- ============================================================

CREATE TABLE IF NOT EXISTS GOLD_3.DIM_LOCN (
    LOCATION_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    STORE_ID NUMBER NOT NULL,
    STORE_NAME VARCHAR,
    STORE_NAME10 VARCHAR,
    STORE_TYPE VARCHAR,
    DISTRICT_ID VARCHAR,
    DISTRICT_NAME VARCHAR,
    REGION_ID VARCHAR,
    REGION_NAME VARCHAR,
    CHANNEL_ID VARCHAR,
    COUNTRY VARCHAR,
    STATE VARCHAR,
    CITY VARCHAR,
    EFFECTIVE_FROM DATE,
    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

ALTER TABLE GOLD_3.DIM_LOCN
    ADD COLUMN IF NOT EXISTS DISTRICT_NAME VARCHAR;

ALTER TABLE GOLD_3.DIM_LOCN
    ADD COLUMN IF NOT EXISTS REGION_ID VARCHAR;

ALTER TABLE GOLD_3.DIM_LOCN
    ADD COLUMN IF NOT EXISTS REGION_NAME VARCHAR;


-- ============================================================
-- 3. DIM_DATE
-- ============================================================

CREATE TABLE IF NOT EXISTS GOLD_3.DIM_DATE (
    DATE_KEY NUMBER NOT NULL,
    FULL_DATE DATE NOT NULL,
    DAY_NUMBER NUMBER,
    DAY_NAME VARCHAR,
    WEEK_NUMBER NUMBER,
    MONTH_NUMBER NUMBER,
    MONTH_NAME VARCHAR,
    QUARTER_NUMBER NUMBER,
    YEAR_NUMBER NUMBER,
    IS_WEEKEND BOOLEAN
);

-- Support existing DIM_DATE table definitions.
ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS DAY_NUMBER NUMBER;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS DAY_NAME VARCHAR;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS WEEK_NUMBER NUMBER;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS MONTH_NUMBER NUMBER;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS MONTH_NAME VARCHAR;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS QUARTER_NUMBER NUMBER;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS YEAR_NUMBER NUMBER;

ALTER TABLE GOLD_3.DIM_DATE
    ADD COLUMN IF NOT EXISTS IS_WEEKEND BOOLEAN;


-- ============================================================
-- 4. FCT_SALES
-- GRAIN: ONE TRANSACTION LINE
-- ============================================================

CREATE TABLE IF NOT EXISTS GOLD_3.FCT_SALES (
    SALES_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    ITEM_KEY NUMBER,
    LOCATION_KEY NUMBER,
    DATE_KEY NUMBER,
    LOCATION_ID NUMBER,
    WORKSTATION_ID NUMBER,
    TRANSACTION_SEQUENCE NUMBER,
    LINE_SEQUENCE NUMBER,
    BUSINESS_DATE DATE,
    BEGIN_DATETIME TIMESTAMP_NTZ,
    TRANSACTION_TYPE VARCHAR,
    ITEM_ID VARCHAR,
    ITEM_SCAN_ID VARCHAR,
    QUANTITY NUMBER(18,3),
    UNIT_PRICE NUMBER(18,2),
    EXTENDED_AMOUNT NUMBER(18,2),
    DISCOUNT_AMOUNT NUMBER(18,2),
    TAX_AMOUNT NUMBER(18,2),
    NET_AMOUNT NUMBER(18,2),
    CURRENCY VARCHAR,
    CASHIER_ID VARCHAR,
    SOURCE_FILE VARCHAR,
    SOURCE_ROW_NUMBER NUMBER,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- ============================================================
-- 5. FCT_INVENTORY
-- GRAIN: ONE ITEM, LOCATION AND SNAPSHOT DATE
-- Historical rows are retained and closed.
-- ============================================================

CREATE TABLE IF NOT EXISTS GOLD_3.FCT_INVENTORY (
    INVENTORY_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    ITEM_KEY NUMBER,
    LOCATION_KEY NUMBER,
    DATE_KEY NUMBER,
    ITEM_ID VARCHAR,
    LOCATION_ID NUMBER,
    SNAPSHOT_DATE DATE,
    STOCK_ON_HAND NUMBER(18,3),
    SOURCE_FILE VARCHAR,
    SOURCE_ROW_NUMBER NUMBER,
    IS_CURRENT BOOLEAN DEFAULT TRUE,
    EFFECTIVE_FROM DATE,
    EFFECTIVE_TO DATE,
    SOURCE_ROW_ID VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

ALTER TABLE GOLD_3.FCT_INVENTORY
    ADD COLUMN IF NOT EXISTS EFFECTIVE_FROM DATE;

ALTER TABLE GOLD_3.FCT_INVENTORY
    ADD COLUMN IF NOT EXISTS EFFECTIVE_TO DATE;

ALTER TABLE GOLD_3.FCT_INVENTORY
    ADD COLUMN IF NOT EXISTS SOURCE_ROW_ID VARCHAR;


